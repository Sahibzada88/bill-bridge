#!/usr/bin/env node
/**
 * Interactive setup: asks for the few values needed and writes .env.local, then runs the doctor.
 *   npm run setup
 * Needed: Supabase URL + anon key + service-role key. Optional: Gmail address + Google App Password.
 */
import { existsSync, copyFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { createInterface } from "node:readline/promises";
import { spawnSync } from "node:child_process";

if (!process.stdin.isTTY) { console.error("Run this in a terminal (it asks questions). Or copy .env.example to .env.local by hand."); process.exit(2); }
const rl = createInterface({ input: process.stdin, output: process.stdout });
const ask = async (q, def = "") => ((await rl.question(def ? `${q} [${def}]: ` : `${q}: `)).trim() || def);

console.log("\nBillBridge setup\n================\nSupabase: Dashboard -> Project Settings -> API (copy the 3 values).\n");
if (existsSync(".env.local")) {
  if ((await ask(".env.local already exists. Overwrite? (y/N)", "N")).toLowerCase() !== "y") { rl.close(); console.log("Kept your .env.local."); process.exit(0); }
  copyFileSync(".env.local", ".env.local.backup");
  console.log("(old file saved as .env.local.backup)");
}
const url = (await ask("1/6 Supabase Project URL (https://xxxx.supabase.co)")).replace(/\/$/, "");
const anon = await ask("2/6 anon / publishable key");
const service = await ask("3/6 service_role / secret key (keep private!)");
const site = await ask("4/6 Site URL (this is where users open the app)", "http://localhost:3000");
console.log("\nGmail is optional (emails for notifications + contact form). Create an App Password at https://myaccount.google.com/apppasswords\n(needs 2-Step Verification). Press Enter to skip.");
const gmail = await ask("5/6 Gmail address", "");
const gpass = gmail ? await ask("6/6 Google App Password (16 letters)") : "";
const backend = (await ask("Where to keep uploaded bills? database = easiest (no Storage setup), storage = Supabase Storage", "database")).toLowerCase() === "storage" ? "storage" : "database";
rl.close();

if (!/^https:\/\/.+\.supabase\.co$/.test(url) && !url.startsWith("http://127.0.0.1") && !url.startsWith("http://localhost")) console.warn("! The URL does not look like https://<ref>.supabase.co - double check.");
const lines = [
  "# Generated by scripts/setup.mjs",
  `NEXT_PUBLIC_SUPABASE_URL=${url}`, `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anon}`, `SUPABASE_SERVICE_ROLE_KEY=${service}`,
  `NEXT_PUBLIC_SITE_URL=${site}`, `STORAGE_BACKEND=${backend}`,
  `GMAIL_USER=${gmail}`, `GMAIL_APP_PASSWORD=${gpass.replace(/\s+/g, "")}`,
  `CRON_SECRET=${randomBytes(24).toString("hex")}`,
  "# Optional later: Cloudflare Turnstile CAPTCHA (see docs/QUICKSTART.md)", "NEXT_PUBLIC_TURNSTILE_SITE_KEY=", "TURNSTILE_SECRET_KEY=", "",
];
writeFileSync(".env.local", lines.join("\n"), { mode: 0o600 });
console.log("\n.env.local written. Checking everything...\n");
spawnSync(process.execPath, ["scripts/doctor.mjs"], { stdio: "inherit" });
