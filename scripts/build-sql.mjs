#!/usr/bin/env node
/** Concatenates supabase/migrations/*.sql into ONE file: supabase/setup_all.sql (paste it once in the SQL Editor). */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "supabase/migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const header = `-- =====================================================================
-- BillBridge: COMPLETE DATABASE SETUP (all migrations in one file)
-- Run this ONCE on a NEW Supabase project: Dashboard -> SQL Editor -> New query -> paste -> Run.
-- It is generated by "npm run build:sql" from supabase/migrations/. Do not edit by hand.
-- Running it twice fails (objects already exist). Use a fresh project or reset the schema first.
-- =====================================================================\n\n`;
const body = files.map((f) => `-- >>>>>>>>>> ${f}\n${readFileSync(path.join(dir, f), "utf8").trim()}\n`).join("\n");
writeFileSync(path.join(process.cwd(), "supabase/setup_all.sql"), header + body);
console.log(`supabase/setup_all.sql written (${files.length} migrations).`);
